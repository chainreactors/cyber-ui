export const fileManagerMessages = {
  en: enFileManagerMessages as FileManagerMessages,
  'zh-CN': zhCNFileManagerMessages,
}

export type FileManagerLocale = keyof typeof fileManagerMessages

export function createFileManagerTranslator(options?: {
  locale?: FileManagerLocale
  messages?: Partial<FileManagerMessages>
}) {
  const locale = options?.locale ?? 'en'
  const dictionary = {
    ...fileManagerMessages[locale],
    ...options?.messages,
  }

  return (key: string, values?: Record<string, unknown>): string => {
    const template = dictionary[key as FileManagerMessageKey] ?? key
    return template.replace(
      /\{(\w+)\}/g,
      (_match, name: string) => String(values?.[name] ?? `{${name}}`),
    )
  }
}
